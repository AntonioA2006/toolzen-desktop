import puppeteer from "/tmp/shot-runner/node_modules/puppeteer-core/lib/esm/puppeteer/puppeteer-core.js";
import fs from "node:fs";
import { execFileSync } from "node:child_process";

const dir = "/opt/cursor/artifacts/redesign";
const fixtures = "/tmp/toolzen-ui/tests/fixtures";
fs.mkdirSync(fixtures, { recursive: true });
execFileSync("python3", ["-c", `from PIL import Image\nImage.new('RGB',(8,8),(255,0,0)).save('${fixtures}/qa.png')`]);
fs.writeFileSync(`${fixtures}/not-image.png`, "not an image");

const browser = await puppeteer.launch({ executablePath: "/usr/local/bin/google-chrome", headless: "new", args: ["--no-sandbox"] });
const page = await browser.newPage();
await page.setViewport({ width: 1280, height: 800 });
await page.goto("http://127.0.0.1:1435/", { waitUntil: "networkidle0" });
await page.evaluate(() => localStorage.clear());
await page.goto("http://127.0.0.1:1435/", { waitUntil: "networkidle0" });
await page.waitForFunction(() => document.body.innerText.includes("Merge PDF") || document.body.innerText.includes("Unir PDF"));
await page.screenshot({ path: `${dir}/dashboard-pass2-light.png` });
const home = await page.evaluate(() => document.body.innerText);
const searchFields = await page.$$("main input, main button");
const mainText = await page.$eval("main", (node) => node.innerText);
if (mainText.includes("Search tools")) throw new Error("duplicate search in the main column");
if (!mainText.includes("not in this build") && !mainText.includes("no están")) throw new Error(mainText.slice(0, 500));
await page.evaluate(() => [...document.querySelectorAll("button")].find((n) => (n.textContent || "").includes("All tools")).click());
await page.waitForFunction(() => document.body.innerText.includes("Compress image") || document.body.innerText.includes("Comprimir imagen"));
await page.evaluate(() => [...document.querySelectorAll("button")].find((n) => (n.textContent || "").includes("☆")).click());
await page.evaluate(() => [...document.querySelectorAll("button")].find((n) => (n.textContent || "").trim() === "Home" || (n.textContent || "").trim() === "Inicio").click());
await page.waitForFunction(() => document.body.innerText.includes("Favorites") || document.body.innerText.includes("Favoritos"));
await page.screenshot({ path: `${dir}/dashboard-favorites-light.png` });
await page.evaluate(() => [...document.querySelectorAll("button")].find((n) => (n.textContent || "").includes("Compress image") || (n.textContent || "").includes("Comprimir imagen")).click());
await page.waitForSelector("input[type=file]");
const input = await page.$("input[type=file]");
await input.uploadFile(`${fixtures}/qa.png`);
await page.waitForFunction(() => document.body.innerText.includes("qa.png"));
await page.screenshot({ path: `${dir}/tool-file-light.png` });
await page.click("button[type=submit]");
await page.waitForFunction(() => document.body.innerText.includes("Save as") || document.body.innerText.includes("Guardar como"), { timeout: 10000 });
await page.screenshot({ path: `${dir}/tool-result-light.png` });
await page.evaluate(() => [...document.querySelectorAll("button")].find((n) => (n.textContent || "").includes("Process another") || (n.textContent || "").includes("Procesar otro")).click());
await input.uploadFile(`${fixtures}/not-image.png`);
await page.click("button[type=submit]");
await page.waitForFunction(() => document.body.innerText.includes("readable") || document.body.innerText.includes("legible") || document.querySelector("[role=alert]"), { timeout: 8000 });
await page.screenshot({ path: `${dir}/tool-error-light.png` });
await page.evaluate(() => [...document.querySelectorAll("button")].find((n) => (n.textContent || "").trim() === "Settings" || (n.textContent || "").trim() === "Ajustes").click());
await page.waitForSelector("select#language");
await page.select("select#language", "es");
await page.waitForFunction(() => document.body.innerText.includes("Ajustes") || document.body.innerText.includes("Apariencia"));
await page.screenshot({ path: `${dir}/settings-es.png` });
await page.evaluate(() => [...document.querySelectorAll("button")].find((n) => (n.textContent || "").trim() === "Inicio").click());
await page.waitForFunction(() => document.body.innerText.includes("Unir PDF") || document.body.innerText.includes("Empieza"));
await page.screenshot({ path: `${dir}/dashboard-es.png` });
const focus = await page.evaluate(() => {
  const button = document.querySelector("main button");
  button.focus();
  const style = getComputedStyle(button);
  return { outline: style.outlineStyle, width: style.outlineWidth };
});
fs.writeFileSync(`${dir}/pass2-notes.json`, JSON.stringify({ focus, homeHasSecondSearch: home.includes("Search tools\n") }, null, 2));
